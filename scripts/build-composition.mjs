const thoughtfulEditorialTimeline = ({ beat, beatId, cues, fps, windowStartFrame, windowEndFrame, wordsById }) => {
  const relativeFrame = (frame) => seconds(frame - windowStartFrame, fps);
  const cueDefinitions = cues.map((cue) => {
    const exitWord = wordsById.get(cue.exitTriggerWordId);
    if (!exitWord) throw new Error(`${beatId}: thoughtful-editorial-v1 exit trigger does not resolve`);
    const exitStartFrame = cue.invisibleFrame === windowEndFrame
      ? cue.invisibleFrame
      : durationToFrames(Number(exitWord.end), fps);
    const initialPhase = windowStartFrame < cue.preMotionFrame ? "pre-motion"
      : windowStartFrame < cue.firstLegibleFrame ? "entering"
        : windowStartFrame < cue.settledFrame ? "settling"
          : windowStartFrame < exitStartFrame ? "visible"
            : windowStartFrame < cue.invisibleFrame ? "exiting"
              : "invisible";
    const initialAutoAlpha = initialPhase === "entering"
      ? 0
      : initialPhase === "exiting"
        ? decimal(1 - (windowStartFrame - exitStartFrame) / Math.max(1, cue.invisibleFrame - exitStartFrame))
        : ["settling", "visible"].includes(initialPhase) ? 1 : 0;
    return {
      id: cue.id,
      preMotion: relativeFrame(cue.preMotionFrame),
      firstLegible: relativeFrame(cue.firstLegibleFrame),
      settled: relativeFrame(cue.settledFrame),
      exitStart: relativeFrame(exitStartFrame),
      invisible: relativeFrame(cue.invisibleFrame),
      initialPhase,
      initialAutoAlpha
    };
  });
  const earliestPreMotion = Math.min(...cueDefinitions.map((cue) => cue.preMotion));
  const latestInvisible = Math.max(...cueDefinitions.map((cue) => cue.invisible));
  const rootVisibleAtWindowStart = earliestPreMotion <= 0 && latestInvisible > 0;
  return [
    `// ${beatId} (${THOUGHTFUL_EDITORIAL_PROFILE})`,
    "{",
    `  const root = document.querySelector(${JSON.stringify(`#mg-${beatId}`)});`,
    `  if (!root) throw new Error(${JSON.stringify(`${beatId}: Beat root is missing`)});`,
    `  const cueFrames = Object.freeze(${JSON.stringify(Object.fromEntries(cueDefinitions.map((cue) => [cue.id, cue])))});`,
    "  const motion = Object.freeze({",
    "    reveal(cueId, options = {}) {",
    "      const cue = cueFrames[cueId];",
    `      if (!cue) throw new Error(${JSON.stringify(`${beatId}: unknown thoughtful-editorial-v1 cue`)} + \" \" + cueId);`,
    "      const allowedOptions = new Set([\"from\", \"legible\", \"settled\", \"exit\"]);",
    "      if (Object.keys(options).some((key) => !allowedOptions.has(key))) throw new Error(\"thoughtful-editorial-v1 reveal timing is builder-owned\");",
    "      const node = cueNodes.get(cueId);",
    `      if (!node) throw new Error(${JSON.stringify(`${beatId}: cue node is missing`)} + \" \" + cueId);`,
    "      const from = options.from && typeof options.from === \"object\" ? options.from : {};",
    "      const legible = options.legible && typeof options.legible === \"object\" ? options.legible : {};",
    "      const settled = options.settled && typeof options.settled === \"object\" ? options.settled : {};",
    "      const exit = options.exit && typeof options.exit === \"object\" ? options.exit : {};",
      "      const allowedVisualProperties = new Set([\"x\", \"y\", \"z\", \"scale\", \"scaleX\", \"scaleY\", \"ease\"]);",
      "      const allowedEases = new Set([\"none\", \"linear\", \"power1.out\", \"power2.out\", \"power3.out\", \"power4.out\", \"sine.out\", \"expo.out\"]);",
      "      for (const values of [from, legible, settled, exit]) {",
      "        if (Object.keys(values).some((key) => !allowedVisualProperties.has(key)) || Object.entries(values).some(([key, value]) => key !== \"ease\" && (!Number.isFinite(value))) || (values.ease !== undefined && !allowedEases.has(String(values.ease)))) {",
      "          throw new Error(\"thoughtful-editorial-v1 reveal options must be allowed visual options\");",
    "        }",
    "      }",
      "      const initial = cue.initialPhase === \"settling\" ? { autoAlpha: cue.initialAutoAlpha, ...legible }",
      "        : cue.initialPhase === \"visible\" || cue.initialPhase === \"exiting\" ? { autoAlpha: cue.initialAutoAlpha, ...settled }",
      "          : cue.initialPhase === \"invisible\" ? { autoAlpha: 0, ...exit } : { autoAlpha: cue.initialAutoAlpha, ...from };",
      "      timeline.set(node, initial, 0);",
      "      if (cue.preMotion > 0) timeline.set(node, { autoAlpha: 0, ...from }, cue.preMotion);",
      "      if (cue.firstLegible > 0) {",
      "        timeline.set(node, { autoAlpha: 1, ...legible }, cue.firstLegible);",
      "      }",
      "      const settleStart = Math.max(cue.firstLegible, 0);",
      "      if (cue.settled > 0) {",
      "        if (cue.settled > settleStart) timeline.to(node, { ...settled, duration: cue.settled - settleStart }, settleStart);",
      "        else timeline.set(node, settled, cue.settled);",
      "      }",
      "      const exitStart = Math.max(cue.exitStart, 0);",
      "      if (cue.invisible > 0) {",
      "        if (cue.invisible > exitStart) timeline.to(node, { autoAlpha: 0, ...exit, duration: cue.invisible - exitStart }, exitStart);",
      "        else timeline.set(node, { autoAlpha: 0, ...exit }, cue.invisible);",
      "      }",
    "    }",
    "  });",
    "  const cueNodes = new Map([...root.querySelectorAll(\"[data-cue-id]\")].map((node) => [node.dataset.cueId, node]));",
    "  timeline.set(root, { autoAlpha: " + (rootVisibleAtWindowStart ? 1 : 0) + " }, 0);",
    "  if (" + earliestPreMotion + " > 0) timeline.set(root, { autoAlpha: 1 }, " + earliestPreMotion + ");",
    "  " + "/* CUT_MOTION_PROFILE_MODULE */",
    "  if (" + latestInvisible + " > 0) timeline.set(root, { autoAlpha: 0 }, " + latestInvisible + ");",
    "}"
  ];
};

const ensureLocalResourceLinks = (compositionDirectory, sourceDirectory) => {
  fs.mkdirSync(compositionDirectory, { recursive: true });
  const stylesheets = fs.readdirSync(sourceDirectory).filter(name => name.endsWith(".css") && fs.statSync(path.join(sourceDirectory, name)).isFile());
  for (const name of new Set(["assets", "caption.css", ...stylesheets])) {
    const source = path.join(sourceDirectory, name);
    if (!fs.existsSync(source)) continue;
    const target = path.join(compositionDirectory, name);
    if (name.endsWith(".css")) {
      if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) fs.unlinkSync(target);
      if (fs.existsSync(target) && !fs.lstatSync(target).isFile()) {
        throw new Error(`Localized ${name} must be a regular file`);
      }
      fs.copyFileSync(source, target);
      continue;
    }
    if (fs.existsSync(target)) {
      if (fs.realpathSync(target) !== fs.realpathSync(source)) {
        throw new Error(`Localized composition resource conflicts with ${name}`);
      }
      continue;
    }
    fs.symlinkSync(
      path.relative(compositionDirectory, source),
      target,
      fs.statSync(source).isDirectory() && process.platform === "win32" ? "junction" : undefined
    );
  }
};

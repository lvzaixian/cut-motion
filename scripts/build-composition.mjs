const stripJavaScriptComments = (source) => {
  let output = "";
  let index = 0;
  while (index < source.length) {
    const character = source[index];
    if (["'", '"', "`"].includes(character)) {
      const quote = character;
      output += character;
      index += 1;
      while (index < source.length) {
        const nested = source[index];
        output += nested;
        index += 1;
        if (nested === "\\" && index < source.length) {
          output += source[index];
          index += 1;
          continue;
        }
        if (nested === quote) break;
      }
      continue;
    }
    if (character === "/" && source[index + 1] === "/") {
      index += 2;
      while (index < source.length && source[index] !== "\n") index += 1;
      continue;
    }
    if (character === "/" && source[index + 1] === "*") {
      const end = source.indexOf("*/", index + 2);
      if (end === -1) throw new Error("thoughtful-editorial-v1 timeline.mjs has an unterminated comment");
      index = end + 2;
      continue;
    }
    output += character;
    index += 1;
  }
  return output;
};
const skipWhitespace = (source, index) => {
  let cursor = index;
  while (cursor < source.length && /\s/.test(source[cursor])) cursor += 1;
  return cursor;
};
const readQuotedLiteral = (source, index, label) => {
  const quote = source[index];
  if (quote !== "'" && quote !== '"') throw new Error(`${label} must be a static quoted string`);
  let value = "";
  let escaped = false;
  let cursor = index + 1;
  while (cursor < source.length) {
    const character = source[cursor];
    if (character === "\\") {
      if (cursor + 1 >= source.length) break;
      escaped = true;
      value += source[cursor + 1];
      cursor += 2;
      continue;
    }
    if (character === quote) return { value, next: cursor + 1, escaped };
    value += character;
    cursor += 1;
  }
  throw new Error(`${label} has an unterminated string`);
};
const readBalancedObject = (source, index, label) => {
  if (source[index] !== "{") throw new Error(`${label} must be an object literal`);
  let depth = 0;
  let cursor = index;
  while (cursor < source.length) {
    const character = source[cursor];
    if (["'", '"', "`"].includes(character)) {
      const literal = readQuotedLiteral(source, cursor, label);
      cursor = literal.next;
      continue;
    }
    if (character === "{") depth += 1;
    if (character === "}") {
      depth -= 1;
      if (depth === 0) return { source: source.slice(index, cursor + 1), next: cursor + 1 };
    }
    cursor += 1;
  }
  throw new Error(`${label} has an unterminated object literal`);
};
const parseThoughtfulRevealCalls = (timeline, beatId) => {
  const source = stripJavaScriptComments(timeline);
  const calls = [];
  let cursor = 0;
  while (cursor < source.length) {
    cursor = skipWhitespace(source, cursor);
    while (source[cursor] === ";") cursor = skipWhitespace(source, cursor + 1);
    if (cursor >= source.length) break;
    if (!source.startsWith("motion.reveal", cursor)
      || /[A-Za-z0-9_$]/.test(source[cursor - 1] ?? "")
      || /[A-Za-z0-9_$]/.test(source[cursor + "motion.reveal".length] ?? "")) {
      throw new Error(`${beatId}: thoughtful-editorial-v1 timeline.mjs must contain only runtime motion.reveal statements`);
    }
    cursor = skipWhitespace(source, cursor + "motion.reveal".length);
    if (source[cursor] !== "(") {
      throw new Error(`${beatId}: thoughtful-editorial-v1 motion.reveal must use a static cue ID`);
    }
    cursor = skipWhitespace(source, cursor + 1);
    const cue = readQuotedLiteral(source, cursor, `${beatId}: thoughtful-editorial-v1 cue ID`);
    cursor = skipWhitespace(source, cue.next);
    let optionsSource = "";
    if (source[cursor] === ",") {
      cursor = skipWhitespace(source, cursor + 1);
      const options = readBalancedObject(source, cursor, `${beatId}: thoughtful-editorial-v1 motion.reveal options`);
      optionsSource = options.source;
      cursor = skipWhitespace(source, options.next);
    }
    if (source[cursor] !== ")") {
      throw new Error(`${beatId}: thoughtful-editorial-v1 motion.reveal must end after its controlled options`);
    }
    calls.push({ cueId: cue.value, optionsSource });
    cursor += 1;
  }
  return calls;
};
const assertThoughtfulRevealOptions = (optionsSource, beatId) => {
  if (!optionsSource) return;
  const allowedStages = new Set(["from", "legible", "settled", "exit"]);
  const allowedVisualProperties = new Set(["x", "y", "z", "scale", "scaleX", "scaleY", "ease"]);
  const allowedEases = new Set(["none", "linear", "power1.out", "power2.out", "power3.out", "power4.out", "sine.out", "expo.out"]);
  let cursor = 0;
  const staticLiteralError = () => new Error(`${beatId}: thoughtful-editorial-v1 reveal options must use static literal values only`);
  const readKey = () => {
    cursor = skipWhitespace(optionsSource, cursor);
    const match = /^[A-Za-z_$][A-Za-z0-9_$]*/.exec(optionsSource.slice(cursor));
    if (!match) throw staticLiteralError();
    cursor += match[0].length;
    return match[0];
  };
  const expect = (character) => {
    cursor = skipWhitespace(optionsSource, cursor);
    if (optionsSource[cursor] !== character) throw staticLiteralError();
    cursor += 1;
  };
  const readLiteral = () => {
    cursor = skipWhitespace(optionsSource, cursor);
    if (optionsSource[cursor] === "'" || optionsSource[cursor] === '"') {
      const literal = readQuotedLiteral(optionsSource, cursor, `${beatId}: thoughtful-editorial-v1 reveal literal`);
      cursor = literal.next;
      return { kind: "string", value: literal.value, escaped: literal.escaped };
    }
    const number = /^-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?/.exec(optionsSource.slice(cursor));
    if (!number || !Number.isFinite(Number(number[0]))) throw staticLiteralError();
    cursor += number[0].length;
    return { kind: "number", value: Number(number[0]) };
  };
  const readVisualObject = () => {
    expect("{");
    cursor = skipWhitespace(optionsSource, cursor);
    if (optionsSource[cursor] === "}") {
      cursor += 1;
      return;
    }
    while (cursor < optionsSource.length) {
      const key = readKey();
      if (!allowedVisualProperties.has(key)) {
        throw new Error(`${beatId}: thoughtful-editorial-v1 reveal option ${key} is not an allowed visual option`);
      }
      expect(":");
      const literal = readLiteral();
      if (key === "ease") {
        if (literal.kind !== "string") throw staticLiteralError();
        if (literal.escaped) throw staticLiteralError();
        if (!allowedEases.has(literal.value)) {
          throw new Error(`${beatId}: thoughtful-editorial-v1 reveal option ease must use an approved editorial ease`);
        }
      } else if (literal.kind !== "number") {
        throw staticLiteralError();
      }
      cursor = skipWhitespace(optionsSource, cursor);
      if (optionsSource[cursor] === "}") {
        cursor += 1;
        return;
      }
      expect(",");
    }
    throw staticLiteralError();
  };
  expect("{");
  cursor = skipWhitespace(optionsSource, cursor);
  if (optionsSource[cursor] === "}") cursor += 1;
  else while (cursor < optionsSource.length) {
    const stage = readKey();
    if (!allowedStages.has(stage)) {
      throw new Error(`${beatId}: thoughtful-editorial-v1 reveal option ${stage} is not an allowed visual option`);
    }
    expect(":");
    readVisualObject();
    cursor = skipWhitespace(optionsSource, cursor);
    if (optionsSource[cursor] === "}") {
      cursor += 1;
      break;
    }
    expect(",");
  }
  if (skipWhitespace(optionsSource, cursor) !== optionsSource.length) throw staticLiteralError();
};
